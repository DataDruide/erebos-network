def _format_timestamp(ts: float) -> str:
    """Formatiert einen Unix-Timestamp als lesbares Datum."""
    import time as _time
    try:
        return _time.strftime("%Y-%m-%d %H:%M", _time.localtime(ts))
    except Exception:
        return "?"


def _escape(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


